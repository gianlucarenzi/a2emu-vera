#!/usr/bin/env python3
"""gendata.py -- data for dblres.s: 16 colour bars in double hi-res and double lo-res.

A double-res colour c is stored rotated right by one bit (the display rotates it back
left, as MAME does): DHGR 4 dots per colour, first dot = bit 0, 7 dots per byte, bytes
alternating aux, main; DLGR aux blocks rotated, main blocks plain.
"""
import sys

def rotr(c):
    return ((c >> 1) | (c << 3)) & 0x0F

# DHGR: 140 colour pixels, 8 per bar (bars 0-15), the last 12 black
dots = []
for p in range(140):
    c = p // 8 if p < 128 else 0
    v = rotr(c)
    dots += [(v >> i) & 1 for i in range(4)]
line = [sum(dots[b * 7 + i] << i for i in range(7)) for b in range(80)]
aux, main = line[0::2], line[1::2]

# DLGR: 80 blocks, 5 per bar; both lo-res rows of a cell the same colour
dl_aux, dl_main = [], []
for col in range(40):
    ca, cm = (2 * col) // 5, (2 * col + 1) // 5
    dl_aux.append(rotr(ca) * 0x11)
    dl_main.append(cm * 0x11)

def hgr(y):
    return 0x2000 + (y & 7) * 0x400 + ((y >> 3) & 7) * 0x80 + (y >> 6) * 0x28

def gr(row):
    return 0x400 + (row & 7) * 0x80 + (row >> 3) * 0x28

def table(name, vals):
    out = [name + ":"]
    for i in range(0, len(vals), 16):
        out.append("        .byte " + ", ".join("$%02X" % v for v in vals[i:i + 16]))
    return "\n".join(out)

print("; generated by gendata.py -- do not edit")
print(table("dh_aux", aux))
print(table("dh_main", main))
print(table("dl_aux", dl_aux))
print(table("dl_main", dl_main))
print(table("hgr_lo", [hgr(y) & 0xFF for y in range(192)]))
print(table("hgr_hi", [hgr(y) >> 8 for y in range(192)]))
print(table("gr_lo", [gr(r) & 0xFF for r in range(24)]))
print(table("gr_hi", [gr(r) >> 8 for r in range(24)]))
